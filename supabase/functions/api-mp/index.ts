import { createClient } from "https://esm.sh/@supabase/supabase-js@2";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-api-key",
  "Access-Control-Allow-Methods": "GET, POST, PUT, OPTIONS",
};

function jsonResponse(data: any, status = 200) {
  return new Response(JSON.stringify(data), {
    status,
    headers: { ...corsHeaders, "Content-Type": "application/json" },
  });
}

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") {
    return new Response(null, { headers: corsHeaders });
  }

  const supabaseUrl = Deno.env.get("SUPABASE_URL")!;
  const serviceRoleKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
  const supabase = createClient(supabaseUrl, serviceRoleKey);

  // Authenticate via X-API-Key header
  const apiKey = req.headers.get("x-api-key");
  if (!apiKey) {
    return jsonResponse({ error: "Header X-API-Key é obrigatório" }, 401);
  }

  const { data: keyData, error: keyError } = await supabase
    .from("api_keys_externas")
    .select("*")
    .eq("api_key", apiKey)
    .eq("ativo", true)
    .single();

  if (keyError || !keyData) {
    return jsonResponse({ error: "API Key inválida ou inativa" }, 403);
  }

  const url = new URL(req.url);
  const path = url.pathname.replace(/^\/api-mp\/?/, "").replace(/^\//, "");

  try {
    // ============================================
    // POST /enviar-inquerito
    // Envia um inquérito — cria registro no sistema
    // ============================================
    if (req.method === "POST" && path === "enviar-inquerito") {
      const body = await req.json();
      const { titulo, conteudo, envolvidos, links, numero_referencia } = body;

      if (!titulo || !conteudo) {
        return jsonResponse({ error: "titulo e conteudo são obrigatórios" }, 400);
      }

      // Build full description with links
      const linksText = links && Array.isArray(links) && links.length > 0
        ? "\n\n📎 Links/Anexos:\n" + links.map((l: any, i: number) => `${i + 1}. ${typeof l === 'string' ? l : (l.url || l.link || JSON.stringify(l))}`).join("\n")
        : "";
      const envolvidosText = envolvidos && Array.isArray(envolvidos) && envolvidos.length > 0
        ? "\n\n👥 Envolvidos:\n" + envolvidos.map((e: any) => `- ${e.nome || 'Desconhecido'} (${e.tipo || 'investigado'})${e.qualificacao ? ' — ' + e.qualificacao : ''}`).join("\n")
        : "";

      // 1. Create actual inquerito record
      const { data: inquerito, error: ipErr } = await supabase.from("inqueritos").insert({
        numero: "", // auto-generated by trigger
        tipo: "criminal",
        descricao: `[${keyData.orgao.toUpperCase()}] ${titulo}\n\n${conteudo}${envolvidosText}${linksText}`,
        data_instauracao: new Date().toISOString(),
        status: "remetido_mp",
        remetido_mp: true,
        sigilo: false,
        relatorio_final: conteudo,
      }).select("id, numero, created_at").single();

      if (ipErr) throw ipErr;

      // 2. Add envolvidos to the inquerito
      if (envolvidos && Array.isArray(envolvidos) && envolvidos.length > 0) {
        const envolvidosInsert = envolvidos.map((e: any) => ({
          inquerito_id: inquerito.id,
          nome: e.nome || "Desconhecido",
          id_personagem: e.id_personagem || null,
          tipo: e.tipo || "investigado",
          qualificacao: e.qualificacao || null,
          observacoes: e.observacoes || null,
        }));
        await supabase.from("envolvidos_inquerito").insert(envolvidosInsert);
      }

      // 3. Create comunicacao_externa linked to inquerito
      const { data: comData, error: comErr } = await supabase.from("comunicacoes_externas").insert({
        api_key_id: keyData.id,
        orgao_origem: keyData.orgao,
        tipo: "inquerito",
        direcao: "entrada",
        titulo,
        conteudo,
        envolvidos: envolvidos || [],
        links: links || [],
        numero_referencia: numero_referencia || null,
        inquerito_id: inquerito.id,
        status: "pendente",
      }).select("id, created_at").single();

      if (comErr) throw comErr;

      return jsonResponse({
        sucesso: true,
        mensagem: "Inquérito enviado ao MP com sucesso e registrado no sistema",
        id: comData.id,
        inquerito_id: inquerito.id,
        inquerito_numero: inquerito.numero,
        criado_em: comData.created_at,
      });
    }

    // ============================================
    // POST /enviar-denuncia
    // Envia uma denúncia — cria inquérito vinculado
    // ============================================
    if (req.method === "POST" && path === "enviar-denuncia") {
      const body = await req.json();
      const { titulo, conteudo, envolvidos, links, numero_referencia } = body;

      if (!titulo || !conteudo) {
        return jsonResponse({ error: "titulo e conteudo são obrigatórios" }, 400);
      }

      // Build full description with links
      const linksText = links && Array.isArray(links) && links.length > 0
        ? "\n\n📎 Links/Anexos:\n" + links.map((l: any, i: number) => `${i + 1}. ${typeof l === 'string' ? l : (l.url || l.link || JSON.stringify(l))}`).join("\n")
        : "";
      const envolvidosText = envolvidos && Array.isArray(envolvidos) && envolvidos.length > 0
        ? "\n\n👥 Envolvidos:\n" + envolvidos.map((e: any) => `- ${e.nome || 'Desconhecido'} (${e.tipo || 'investigado'})${e.qualificacao ? ' — ' + e.qualificacao : ''}`).join("\n")
        : "";

      // 1. Create actual inquerito record
      const { data: inquerito, error: ipErr } = await supabase.from("inqueritos").insert({
        numero: "",
        tipo: "criminal",
        descricao: `[DENÚNCIA - ${keyData.orgao.toUpperCase()}] ${titulo}\n\n${conteudo}${envolvidosText}${linksText}`,
        data_instauracao: new Date().toISOString(),
        status: "remetido_mp",
        remetido_mp: true,
        sigilo: false,
        relatorio_final: conteudo,
      }).select("id, numero, created_at").single();

      if (ipErr) throw ipErr;

      // 2. Add envolvidos
      if (envolvidos && Array.isArray(envolvidos) && envolvidos.length > 0) {
        const envolvidosInsert = envolvidos.map((e: any) => ({
          inquerito_id: inquerito.id,
          nome: e.nome || "Desconhecido",
          id_personagem: e.id_personagem || null,
          tipo: e.tipo || "investigado",
          qualificacao: e.qualificacao || null,
          observacoes: e.observacoes || null,
        }));
        await supabase.from("envolvidos_inquerito").insert(envolvidosInsert);
      }

      // 3. Create comunicacao
      const { data: comData, error: comErr } = await supabase.from("comunicacoes_externas").insert({
        api_key_id: keyData.id,
        orgao_origem: keyData.orgao,
        tipo: "denuncia",
        direcao: "entrada",
        titulo,
        conteudo,
        envolvidos: envolvidos || [],
        links: links || [],
        numero_referencia: numero_referencia || null,
        inquerito_id: inquerito.id,
        status: "pendente",
      }).select("id, created_at").single();

      if (comErr) throw comErr;

      return jsonResponse({
        sucesso: true,
        mensagem: "Denúncia enviada ao MP com sucesso e inquérito instaurado",
        id: comData.id,
        inquerito_id: inquerito.id,
        inquerito_numero: inquerito.numero,
        criado_em: comData.created_at,
      });
    }

    // ============================================
    // POST /enviar-comunicacao
    // Comunicação genérica (atrelada a inquérito se informado)
    // ============================================
    if (req.method === "POST" && path === "enviar-comunicacao") {
      const body = await req.json();
      const { titulo, conteudo, envolvidos, links, numero_referencia, resposta_a, inquerito_id } = body;

      if (!titulo || !conteudo) {
        return jsonResponse({ error: "titulo e conteudo são obrigatórios" }, 400);
      }

      // Validate inquerito_id if provided
      let linkedInqueritoId = inquerito_id || null;
      if (resposta_a && !linkedInqueritoId) {
        // Try to find inquerito from the original communication
        const { data: original } = await supabase
          .from("comunicacoes_externas")
          .select("inquerito_id")
          .eq("id", resposta_a)
          .single();
        if (original?.inquerito_id) {
          linkedInqueritoId = original.inquerito_id;
        }
      }

      const { data, error } = await supabase.from("comunicacoes_externas").insert({
        api_key_id: keyData.id,
        orgao_origem: keyData.orgao,
        tipo: "comunicacao",
        direcao: "entrada",
        titulo,
        conteudo,
        envolvidos: envolvidos || [],
        links: links || [],
        numero_referencia: numero_referencia || null,
        resposta_a: resposta_a || null,
        inquerito_id: linkedInqueritoId,
        status: "pendente",
      }).select("id, created_at").single();

      if (error) throw error;
      return jsonResponse({
        sucesso: true,
        mensagem: "Comunicação enviada ao MP com sucesso",
        id: data.id,
        inquerito_id: linkedInqueritoId,
        criado_em: data.created_at,
      });
    }

    // ============================================
    // GET /comunicacoes
    // Lista comunicações do MP para o órgão (saída)
    // ============================================
    if (req.method === "GET" && path === "comunicacoes") {
      const status = url.searchParams.get("status");
      const desde = url.searchParams.get("desde");
      const limite = parseInt(url.searchParams.get("limite") || "50");
      const pagina = parseInt(url.searchParams.get("pagina") || "1");

      let query = supabase
        .from("comunicacoes_externas")
        .select("id, tipo, direcao, titulo, conteudo, envolvidos, links, numero_referencia, status, resposta_a, inquerito_id, created_at, updated_at", { count: "exact" })
        .eq("api_key_id", keyData.id)
        .eq("direcao", "saida")
        .order("created_at", { ascending: false })
        .range((pagina - 1) * limite, pagina * limite - 1);

      if (status) query = query.eq("status", status);
      if (desde) query = query.gte("created_at", desde);

      const { data, error, count } = await query;
      if (error) throw error;

      return jsonResponse({ comunicacoes: data, total: count, pagina, limite });
    }

    // ============================================
    // GET /comunicacoes/:id
    // Busca uma comunicação específica
    // ============================================
    if (req.method === "GET" && path.startsWith("comunicacoes/")) {
      const id = path.replace("comunicacoes/", "");

      const { data, error } = await supabase
        .from("comunicacoes_externas")
        .select("*")
        .eq("id", id)
        .eq("api_key_id", keyData.id)
        .single();

      if (error || !data) {
        return jsonResponse({ error: "Comunicação não encontrada" }, 404);
      }

      return jsonResponse(data);
    }

    // ============================================
    // GET /meus-inqueritos
    // Lista inquéritos enviados por este órgão
    // ============================================
    if (req.method === "GET" && path === "meus-inqueritos") {
      const limite = parseInt(url.searchParams.get("limite") || "50");
      const pagina = parseInt(url.searchParams.get("pagina") || "1");

      // Get inquerito IDs linked to this API key
      const { data: coms, error: comErr } = await supabase
        .from("comunicacoes_externas")
        .select("inquerito_id")
        .eq("api_key_id", keyData.id)
        .not("inquerito_id", "is", null)
        .in("tipo", ["inquerito", "denuncia"]);

      if (comErr) throw comErr;

      const inqueritoIds = [...new Set((coms || []).map((c: any) => c.inquerito_id).filter(Boolean))];

      if (inqueritoIds.length === 0) {
        return jsonResponse({ inqueritos: [], total: 0, pagina, limite });
      }

      const { data, error, count } = await supabase
        .from("inqueritos")
        .select("id, numero, tipo, descricao, status, remetido_mp, data_instauracao, data_conclusao, created_at, updated_at", { count: "exact" })
        .in("id", inqueritoIds)
        .order("created_at", { ascending: false })
        .range((pagina - 1) * limite, pagina * limite - 1);

      if (error) throw error;

      return jsonResponse({ inqueritos: data, total: count, pagina, limite });
    }

    // ============================================
    // GET /inquerito/:id
    // Acompanha o andamento de um inquérito específico
    // ============================================
    if (req.method === "GET" && path.startsWith("inquerito/")) {
      const id = path.replace("inquerito/", "");

      // Verify this inquerito belongs to this API key
      const { data: linkCheck } = await supabase
        .from("comunicacoes_externas")
        .select("id")
        .eq("api_key_id", keyData.id)
        .eq("inquerito_id", id)
        .limit(1);

      if (!linkCheck || linkCheck.length === 0) {
        return jsonResponse({ error: "Inquérito não encontrado ou não pertence a este órgão" }, 404);
      }

      // Fetch inquerito
      const { data: inquerito, error: ipErr } = await supabase
        .from("inqueritos")
        .select("id, numero, tipo, descricao, status, remetido_mp, data_instauracao, data_conclusao, relatorio_final, created_at, updated_at")
        .eq("id", id)
        .single();

      if (ipErr || !inquerito) {
        return jsonResponse({ error: "Inquérito não encontrado" }, 404);
      }

      // Fetch envolvidos
      const { data: envolvidos } = await supabase
        .from("envolvidos_inquerito")
        .select("nome, tipo, id_personagem, qualificacao, observacoes")
        .eq("inquerito_id", id);

      // Fetch diligências
      const { data: diligencias } = await supabase
        .from("diligencias")
        .select("tipo, descricao, status, resultado, created_at")
        .eq("inquerito_id", id)
        .order("created_at", { ascending: false });

      // Fetch requisições do MP
      const { data: requisicoes } = await supabase
        .from("requisicoes_diligencia_mp")
        .select("descricao, prazo_dias, status, resposta, created_at")
        .eq("inquerito_id", id)
        .order("created_at", { ascending: false });

      // Fetch communications related to this inquerito
      const { data: comunicacoes } = await supabase
        .from("comunicacoes_externas")
        .select("id, tipo, direcao, titulo, conteudo, status, created_at")
        .eq("inquerito_id", id)
        .order("created_at", { ascending: false });

      // Check if denuncia was offered
      const { data: denuncias } = await supabase
        .from("denuncias_mp")
        .select("numero_protocolo, resumo, tipificacao, status, processo_id, created_at")
        .eq("inquerito_id", id);

      // Check if archived
      const { data: arquivamentos } = await supabase
        .from("arquivamentos_mp")
        .select("justificativa, status, created_at")
        .eq("inquerito_id", id);

      return jsonResponse({
        inquerito,
        envolvidos: envolvidos || [],
        diligencias: diligencias || [],
        requisicoes_mp: requisicoes || [],
        comunicacoes: comunicacoes || [],
        denuncias: denuncias || [],
        arquivamentos: arquivamentos || [],
      });
    }

    // ============================================
    // PUT /marcar-lido/:id
    // Marca uma comunicação de saída como lida
    // ============================================
    if (req.method === "PUT" && path.startsWith("marcar-lido/")) {
      const id = path.replace("marcar-lido/", "");

      const { data, error } = await supabase
        .from("comunicacoes_externas")
        .update({ status: "lido", lido_em: new Date().toISOString() })
        .eq("id", id)
        .eq("api_key_id", keyData.id)
        .eq("direcao", "saida")
        .select("id")
        .single();

      if (error || !data) {
        return jsonResponse({ error: "Comunicação não encontrada" }, 404);
      }

      return jsonResponse({ sucesso: true, mensagem: "Marcado como lido" });
    }

    // ============================================
    // GET /status
    // ============================================
    if (req.method === "GET" && path === "status") {
      return jsonResponse({
        status: "online",
        orgao: keyData.orgao,
        sistema: keyData.nome_sistema,
        versao_api: "2.1.0",
      });
    }

    // ============================================
    // PUT /atualizar-diligencia/:id
    // Atualiza status/resultado de uma requisição de diligência
    // ============================================
    if (req.method === "PUT" && path.startsWith("atualizar-diligencia/")) {
      const id = path.replace("atualizar-diligencia/", "");
      const body = await req.json();
      const { status: newStatus, resposta, resultado } = body;

      if (!newStatus && !resposta && !resultado) {
        return jsonResponse({ error: "Informe ao menos status, resposta ou resultado" }, 400);
      }

      // Verify this requisição belongs to an inquerito linked to this API key
      const { data: req_data, error: req_err } = await supabase
        .from("requisicoes_diligencia_mp")
        .select("id, inquerito_id")
        .eq("id", id)
        .single();

      if (req_err || !req_data) {
        return jsonResponse({ error: "Requisição de diligência não encontrada" }, 404);
      }

      // Verify inquerito belongs to this API key
      const { data: linkCheck } = await supabase
        .from("comunicacoes_externas")
        .select("id")
        .eq("api_key_id", keyData.id)
        .eq("inquerito_id", req_data.inquerito_id)
        .limit(1);

      if (!linkCheck || linkCheck.length === 0) {
        return jsonResponse({ error: "Requisição não pertence a um inquérito deste órgão" }, 403);
      }

      // Update requisição
      const updateData: any = { updated_at: new Date().toISOString() };
      if (newStatus) updateData.status = newStatus;
      if (resposta) updateData.resposta = resposta;

      const { error: updateErr } = await supabase
        .from("requisicoes_diligencia_mp")
        .update(updateData)
        .eq("id", id);

      if (updateErr) throw updateErr;

      // Also update linked diligência if resultado provided
      if (resultado) {
        const { data: diligencia } = await supabase
          .from("diligencias")
          .select("id")
          .eq("inquerito_id", req_data.inquerito_id)
          .order("created_at", { ascending: false })
          .limit(1);

        if (diligencia && diligencia.length > 0) {
          await supabase
            .from("diligencias")
            .update({ resultado, status: newStatus || "concluida" })
            .eq("id", diligencia[0].id);
        }
      }

      return jsonResponse({
        sucesso: true,
        mensagem: "Diligência atualizada com sucesso",
      });
    }

    return jsonResponse({
      error: "Rota não encontrada.",
      rotas_disponiveis: [
        "POST /enviar-inquerito — Envia inquérito (cria registro no sistema do MP)",
        "POST /enviar-denuncia — Envia denúncia (cria inquérito vinculado)",
        "POST /enviar-comunicacao — Comunicação genérica (pode vincular a inquérito)",
        "GET /comunicacoes — Lista comunicações do MP para seu órgão",
        "GET /comunicacoes/:id — Busca comunicação específica",
        "GET /meus-inqueritos — Lista inquéritos enviados por este órgão",
        "GET /inquerito/:id — Acompanha andamento completo de um inquérito",
        "PUT /marcar-lido/:id — Marca comunicação como lida",
        "PUT /atualizar-diligencia/:id — Atualiza status/resultado de diligência requisitada",
        "GET /status — Status da API",
      ],
    }, 404);
  } catch (err) {
    console.error("API MP Error:", err);
    return jsonResponse({ error: "Erro interno do servidor", detalhes: err.message }, 500);
  }
});
